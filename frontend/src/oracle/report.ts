/**
 * The generated oracle report (`docs/oracle.md`). Pure rendering: the suite
 * hands it one entry per case with the run's measures, and the meta-test and
 * the drift check compare the committed file against this output, exactly the
 * way `commandRows.ts` feeds docs/command_system.md.
 *
 * Every number in the file is reproducible: the measured values come from the
 * real kernel (WASM floating point is deterministic), the expected values come
 * from the corpus, and nothing here reads a clock or a path.
 */

import type { OracleExpected, OracleMeasures } from './corpus'
import type { MeasureRecord } from '@/kernel/occ/measure'

/** One case's run, reduced to what the report renders. */
export interface CaseReport {
  name: string
  expected: OracleExpected
  live: MeasureRecord
  step: MeasureRecord
  edited: { live: MeasureRecord; step: MeasureRecord } | null
  ok: boolean
}

function fmt(x: number): string {
  if (!Number.isFinite(x)) return 'none'
  // Nine significant digits: far more than the 1e-6 budget, far less than the
  // last bit of the integrator's converged value.
  return x.toPrecision(9)
}

function fmtVec(v: readonly number[]): string {
  return `[${v.map(fmt).join(', ')}]`
}

function dev(measured: number, expected: number): string {
  const d = measured - expected
  if (d === 0) return '0'
  return d.toExponential(2)
}

function relDev(measured: number, expected: number): string {
  if (expected === 0) return dev(measured, expected)
  const d = (measured - expected) / Math.abs(expected)
  if (d === 0) return '0'
  return d.toExponential(2)
}

function maxVecDev(measured: readonly number[], expected: readonly number[]): string {
  let max = 0
  for (let i = 0; i < Math.max(measured.length, expected.length); i++) {
    max = Math.max(max, Math.abs((measured[i] ?? 0) - (expected[i] ?? 0)))
  }
  return max === 0 ? '0' : max.toExponential(2)
}

function counts(expected: OracleMeasures): string {
  const parts: string[] = []
  if (expected.faces !== undefined) parts.push(`faces ${expected.faces}`)
  if (expected.edges !== undefined) parts.push(`edges ${expected.edges}`)
  return parts.length > 0 ? parts.join(', ') : '-'
}

function vectorLine(label: string, measured: readonly number[] | null, expected: readonly number[]): string {
  const shown = measured === null ? 'none' : `${fmtVec(measured)} (max dev ${maxVecDev(measured, expected)})`
  return `  - ${label} ${fmtVec(expected)} -> ${shown}`
}

function measureLines(measured: MeasureRecord, expected: OracleMeasures): string[] {
  const lines = [
    `  - volume ${fmt(expected.volume)} -> ${fmt(measured.volume)} (rel dev ${relDev(measured.volume, expected.volume)})`,
    `  - area ${fmt(expected.area)} -> ${fmt(measured.area)} (rel dev ${relDev(measured.area, expected.area)})`,
    vectorLine('centroid', measured.centroid, expected.centroid),
    vectorLine('bbox', measured.bbox, expected.bbox),
  ]
  if (expected.faces !== undefined || expected.edges !== undefined) {
    lines.push(
      `  - counts ${counts(expected)} -> faces ${measured.faces}, edges ${measured.edges}`,
    )
  }
  return lines
}

/**
 * The whole report. The layout section is part of the rendered text on
 * purpose: it is the contract the sibling minimised-recipe feature needs, and
 * keeping it generated means it cannot drift from the loader's behaviour.
 */
export function renderOracleReport(reports: CaseReport[]): string {
  const header = [
    '# Reference Oracle',
    '',
    'An independent geometric truth set for the kernel. Every case states its',
    'formula in `expected.json`, the runner builds the recipe through the real',
    'loader and solver pipeline, and the measures (volume, area, centroid, bbox,',
    'face/edge counts) must match the formula and survive a STEP round trip.',
    '',
    `Generated by \`npm run docs:oracle\` (same suite with \`UPDATE_ORACLE_DOCS=1\`).`,
    'Do not edit by hand: the drift check',
    '(`src/oracle/__tests__/oracleReal.test.ts`) fails when this file is stale,',
    'and every measure is re-asserted on each provisioned run.',
    '',
    '## Layout',
    '',
    'One directory per case: `frontend/oracle/<NN-name>/`.',
    '',
    '- `recipe.yaml`: a normal Oversolved part document (same loader as a stored',
    '  part), built by the real kernel.',
    '- `expected.json`: `{ method, bodies, volume, area, centroid, bbox, faces?,',
    '  edges?, edit? }`. Volume/area/centroid/bbox are closed-form; `method` is',
    '  the formula as a sentence; `edit` optionally edits an upstream feature',
    '  field and states the edited state\'s expectation plus its own `method`.',
    '- A sibling feature may drop minimised recipes in beside these (one',
    '  directory per recipe, same two files); the meta-test enforces both files,',
    '  a non-empty `method`, and a section in this report.',
    '',
    '## Summary',
    '',
    '| Case | Bodies | Volume | Area | Counts | Edit | Status |',
    '|---|---|---|---|---|---|---|',
  ]
  const rows = reports.map((r) => {
    const status = r.ok ? 'ok' : 'FAIL'
    const edit = r.edited === null ? '-' : (r.ok ? 'ok' : 'FAIL')
    return `| ${r.name} | ${r.expected.bodies} | ${fmt(r.expected.volume)} | ${fmt(r.expected.area)} | ${counts(r.expected)} | ${edit} | ${status} |`
  })
  const sections: string[] = []
  for (const r of reports) {
    const lines = [`### ${r.name}`, '', `\`${r.expected.method}\``, '']
    lines.push('Live build (expected -> measured):', ...measureLines(r.live, r.expected))
    lines.push('', 'STEP round trip:', ...measureLines(r.step, r.expected))
    if (r.edited !== null && r.expected.edit !== undefined) {
      const edit = r.expected.edit
      lines.push(
        '',
        `Edit: \`${edit.what}\` (${edit.feature}.${edit.field} = ${edit.value}).`,
        `\`${edit.method}\``,
        '',
        ...measureLines(r.edited.live, { ...edit.expect, bodies: edit.expect.bodies }),
      )
      lines.push('', 'Edit STEP round trip:', ...measureLines(r.edited.step, edit.expect))
    }
    sections.push(lines.join('\n'))
  }
  return [...header, ...rows, '', '## Cases', '', ...sections, ''].join('\n')
}
